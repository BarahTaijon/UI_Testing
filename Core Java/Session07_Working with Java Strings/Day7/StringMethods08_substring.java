package Day7;

public class StringMethods08_substring {

	public static void main(String[] args) {
		
		// first parameter: the start index
	   // second one: the length token
		
		String s = "welcome to selenium java selenium python";

		System.out.println(s.substring(0,5)); //welco
		System.out.println(s.substring(5,15)); //me to sele
	}

}
