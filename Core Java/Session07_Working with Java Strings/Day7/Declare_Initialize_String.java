package Day7;

public class Declare_Initialize_String {

	public static void main(String[] args) {
		// to declare string in java:
		String s;
		String s1 = new String();
		
		// to initialize string:
		s = "Helo";
		s1 = new String(" World");
		
		System.out.println(s + s1);

	}

}
