package Day3;

public class Assignment_Operatror_Demo {

	public static void main(String[] args) {
		
		int a = 10;
		
		a += 5;		// equivalent to 	a = a+5
		System.out.println(a);
		
		a -= 5;		// equivalent to 	a = a-5
		System.out.println(a);
		
		a *= 2;		// equivalent to 	a = a*5
		System.out.println(a);
		
		a /= 5;		// equivalent to 	a = a/5
		System.out.println(a);
		

	}

}
