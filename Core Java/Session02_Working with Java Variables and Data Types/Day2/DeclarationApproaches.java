package Day2;

public class DeclarationApproaches {

	public static void main(String[] args) {
		
		//different approaches to declaration and assignment 
		
		//Approach 1 - if all variables belongs to different data types 
		int a = 100;
		int b = 200;
		int c = 300;
		
		// Approach 2 - if all variables belongs to same data types 
		int d, e, f; 
		d = 100;
		e = 200;
		f = 300;
		
		// Approach 3 - if all variables belongs to same data types 
		int g = 100, h = 200, i = 300;
		
	}
}
